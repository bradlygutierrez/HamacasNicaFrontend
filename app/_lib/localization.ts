function getCurrentLanguage(): AppLanguage {
  return typeof window !== "undefined" &&
    document.documentElement.dataset.preferencesReady === "true" &&
    window.localStorage.getItem("hamacas:language") === "en"
      ? "en"
      : "es";
}

export function translateText(text: string): string {
  const language = getCurrentLanguage();
  if (language !== "en") return text;

  const match = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return text;

  const [, leading, content, trailing] = match;
  const key = content.replace(/\s+/g, " ").trim();
  return `${leading}${ENGLISH_TRANSLATIONS[key] ?? content}${trailing}`;
}
